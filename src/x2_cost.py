"""[보조 분석] 4단계: 비용 민감도 — 발행비용률과 투자자 순지급수익률.

비용 파라미터는 x2_common.COST (사용자가 확인한 2023년 투자설명서 ANL 수치). 모두 가정값이다.
"""
import warnings
import pandas as pd
from engine import run, apply_A, PhaseData, bundle_metrics
from x2_common import TAG, LG, FINAL, COST, tsave
import numpy as np

warnings.filterwarnings("ignore")
C = COST
assert C["위탁수익금"] + C["신탁보수"] + C["상장수수료"] + C["기타"] == C["공모총액"], "공모총액 구성 불일치"
N = 20
NOTE = "가정값이며 실제 수수료 구조는 최신 투자설명서로 확인해야 함"

# ============================================================ 4-1 발행비용률
rows = [{"구분": "단일곡(투자설명서 수치)", "위탁수익금": C["위탁수익금"], "신탁보수": C["신탁보수"], "상장수수료": C["상장수수료"],
         "기타": C["기타"], "공모총액": C["공모총액"], "발행비용률": (C["공모총액"] - C["위탁수익금"]) / C["공모총액"],
         "상장수수료_산정": "투자설명서 금액(공모총액의 %.2f%%)" % (C["상장수수료"] / C["공모총액"] * 100)}]
for mult in (1, 3, 5):
    W, T, O = N * C["위탁수익금"], mult * C["신탁보수"], N * C["기타"]
    F = (W + T + O) / (1 - C["상장수수료율"])          # 기본안: 상장수수료 = 묶음 공모총액의 2%
    rows.append({"구분": f"20곡 묶음, 신탁보수 {mult}배", "위탁수익금": W, "신탁보수": T, "상장수수료": F * C["상장수수료율"], "기타": O,
                 "공모총액": F, "발행비용률": (F - W) / F, "상장수수료_산정": "기본안: 묶음 공모총액의 2%"})
    L = N * C["상장수수료"]                              # 대안: 단일곡 상장수수료 × 20
    F2 = W + T + O + L
    rows.append({"구분": f"20곡 묶음, 신탁보수 {mult}배 (대안)", "위탁수익금": W, "신탁보수": T, "상장수수료": L, "기타": O,
                 "공모총액": F2, "발행비용률": (F2 - W) / F2, "상장수수료_산정": "대안: 단일곡 상장수수료 × 20"})
T24 = pd.DataFrame(rows)
T24["발행비용률(%)"] = (T24.pop("발행비용률") * 100).round(3)
for c in ["위탁수익금", "신탁보수", "상장수수료", "기타", "공모총액"]:
    T24[c] = T24[c].round(0).astype(int)
T24["주석"] = NOTE
tsave(T24, "3-24_발행비용률")

# ============================================================ 4-2 순지급수익률
ANN = {"P1": 1.0, "P2": 1.0, "P2b": 12 / 8}
fees = [0.0, 0.03, 0.05, 0.10, 0.15]
costs = {r["구분"]: r["발행비용률(%)"] / 100 for _, r in T24.iterrows()}
gross, single = {}, {}
for pk in ["P1", "P2", "P2b"]:
    r = run(pk, FINAL)
    gross[pk] = (r["평균지급수익률"] * ANN[pk], r["지급수익률_p5"] * ANN[pk])
    P = PhaseData(pk)
    ids = np.asarray(apply_A(P.sel, FINAL["A"])).reshape(-1, 1)
    y = bundle_metrics(P, ids, np.ones_like(ids, dtype=float))["yield"] * ANN[pk]
    single[pk] = (y.mean(), y.quantile(.05))
rows = []
for pk, (gm, g5) in gross.items():
    for cname, cr in costs.items():
        for f in fees:
            rows.append({"기간": pk, "총지급수익률_평균(%)": gm * 100, "총지급수익률_p5(%)": g5 * 100, "발행비용 가정": cname,
                         "발행비용률(%)": cr * 100, "연보수율(저작권료대비,%)": f * 100,
                         "순지급수익률_평균(%)": gm * (1 - f) * (1 - cr) * 100, "순지급수익률_p5(%)": g5 * (1 - f) * (1 - cr) * 100})
T25 = pd.DataFrame(rows).round(3)
tsave(T25, "3-25_순지급수익률")
# 핵심 요약: 기본안(신탁보수 1배) 묶음 vs 단일곡, 보수 0·5·10%
key = []
for pk in gross:
    for f in (0.0, 0.05, 0.10):
        b1 = costs["20곡 묶음, 신탁보수 1배"]; s1 = costs["단일곡(투자설명서 수치)"]
        key.append({"기간": pk, "연보수율(%)": f * 100,
                    "최종묶음_순수익률_평균(%,비용 기본안)": gross[pk][0] * (1 - f) * (1 - b1) * 100,
                    "최종묶음_순수익률_p5(%)": gross[pk][1] * (1 - f) * (1 - b1) * 100,
                    "단일곡_순수익률_평균(%,단일곡 비용)": single[pk][0] * (1 - f) * (1 - s1) * 100,
                    "단일곡_순수익률_p5(%)": single[pk][1] * (1 - f) * (1 - s1) * 100})
T25b = pd.DataFrame(key).round(3)
tsave(T25b, "3-25b_순지급수익률_묶음vs단일곡_요약")
log = [f"# [{TAG}] 보강 4단계: 비용 민감도\n",
       "- 비용 파라미터(사용자 확인, 2023년 투자설명서 ANL): 공모총액 40,208,000 = 위탁수익금 37,181,848 + 신탁보수 2,000,000 + 상장수수료 772,912 + 기타 253,240 (합계 검산 일치). "
       "파라미터는 `src/x2_common.py`의 COST에 두었다(기존 `config.py`는 수정하지 않음).",
       "- 20곡 묶음 가정: 위탁수익금 = 20 × 37,181,848, 신탁보수 = 1회분(민감도 3·5배), 기타 = 20배. 상장수수료 '2%'는 기준이 명시되지 않아 "
       "기본안을 묶음 공모총액의 2%(공모총액 = (위탁+신탁+기타) ÷ 0.98)로, 대안을 단일곡 상장수수료 × 20으로 계산했다. 단일곡 상장수수료는 공모총액의 1.92%다.",
       f"- **{NOTE}.**\n", "## 4-1. 발행비용률 (표 3-24)\n", T24.drop(columns="주석").to_markdown(index=False), "",
       "## 4-2. 순지급수익률 (표 3-25, 3-25b)\n",
       "- 순지급수익률 = 총 지급수익률 × (1 − 연 보수율) × (1 − 발행비용률). 총 지급수익률은 최종 묶음 3,000개의 평균·p5(2026은 12/8 연환산).",
       "- 3-25b는 비용 기본안(신탁보수 1배)의 묶음과, 투자설명서 비용률의 단일곡(같은 A3 적격 기준)을 나란히 둔 요약이다.",
       T25b.to_markdown(index=False), ""]
(LG / "23_비용민감도.md").write_text("\n".join(log), encoding="utf-8")
print("\n".join(log))
